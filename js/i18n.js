export const LANGUAGES = [["pt-BR", "PT"], ["en", "EN"]];
let current = "pt-BR";

export const getLang = () => current;
export const setLang = (lang) => { current = MESSAGES[lang] ? lang : "pt-BR"; };

export function t(key, params = {}) {
  const template = MESSAGES[current][key] ?? MESSAGES["pt-BR"][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

// Static markup: data-i18n sets text, data-i18n-<attr> sets that attribute.
export function translateDocument(root = document) {
  document.documentElement.lang = current;
  document.title = t("doc.title");
  root.querySelectorAll("[data-i18n], [data-i18n-aria-label], [data-i18n-title]").forEach((element) => {
    for (const { name, value } of [...element.attributes]) {
      if (name === "data-i18n") element.textContent = t(value);
      else if (name.startsWith("data-i18n-")) element.setAttribute(name.slice("data-i18n-".length), t(value));
    }
  });
}
